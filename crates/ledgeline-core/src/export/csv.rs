//! Posting-row CSV, byte-compatible with hledger 1.52's `print --auto -O csv`.
//!
//! One row per posting amount, every field double-quoted, `""` for an
//! embedded quote, `\n` line endings, and a header row. The column order is
//! [`HEADER`] — the order the bundled hledger 1.52 writes, verified against
//! it. Note that 1.52 writes `credit` BEFORE `debit`; hledger 1.99.4 swapped
//! the two, and Ledgeline matches the version it bundles.
//!
//! What each column holds, as hledger fills it:
//!
//! - `txnidx` — the transaction's 1-based position in parse order (hledger's
//!   `tindex`). Rows are written in `print` order (by date, ties in file
//!   order), so this is not always ascending. It is the grouping key a
//!   posting-row importer reads.
//! - `date`, `date2` — ISO dates; `date2` empty when there is none.
//! - `status`, `posting-status` — `*`, `!` or empty.
//! - `code`, `description` — as written (`description` is never split at `|`).
//! - `comment`, `posting-comment` — the raw comment text, tags included, with
//!   continuation lines joined by a newline inside the quoted field and
//!   surrounding whitespace trimmed. A posting generated by an `=` rule gets
//!   its inherited posting date in front, as `[DATE]` (see
//!   [`posting_comment`]).
//! - `account` — wrapped in `()` / `[]` for a virtual posting.
//! - `amount` — the bare quantity at its display precision, with the
//!   commodity's decimal mark and no digit grouping; `commodity` holds the
//!   symbol. A zero is always `0`, and a zero commodity inside a mixed amount
//!   is left out, as hledger's display drops it.
//! - `credit` / `debit` — the magnitude in exactly one of them: `credit` for a
//!   negative amount, `debit` otherwise (a zero is a debit of `0`).
//!
//! A posting with a mixed amount (an inferred leg balancing two commodities)
//! is one row per commodity. Costs (`@`/`@@`) and balance assertions have no
//! column and are not written — hledger drops them the same way.

use super::print_order;
use crate::auto::apply_journal;
use crate::decimal::Dec;
use crate::edit::render_dec;
use crate::model::{Amount, Journal, Posting, PostingType, Status, Transaction};

/// The header row, in hledger 1.52's column order.
pub const HEADER: [&str; 14] = [
    "txnidx",
    "date",
    "date2",
    "status",
    "code",
    "description",
    "comment",
    "account",
    "amount",
    "commodity",
    "credit",
    "debit",
    "posting-status",
    "posting-comment",
];

/// What [`export_csv`] wrote.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CsvExport {
    /// The CSV text, header included, ending in a newline.
    pub text: String,
    /// Transactions written.
    pub transactions: usize,
    /// Data rows written (one per posting amount).
    pub rows: usize,
}

/// `journal`, with its auto-posting rules applied, as hledger 1.52's
/// `print --auto -O csv` would write it.
#[must_use]
pub fn export_csv(journal: &Journal) -> CsvExport {
    let applied = apply_journal(journal);
    let ordered = print_order(&applied);
    let mut text = csv_line(HEADER.iter().copied());
    let mut rows = 0;
    for txn in &ordered {
        for posting in &txn.postings {
            for row in posting_rows(txn, posting) {
                text.push_str(&csv_line(row.iter().map(String::as_str)));
                rows += 1;
            }
        }
    }
    CsvExport {
        text,
        transactions: ordered.len(),
        rows,
    }
}

/// The rows one posting contributes: one per amount, or a single zero row for
/// a posting with no amount at all (hledger shows an empty mixed amount as
/// `0`).
fn posting_rows(txn: &Transaction, posting: &Posting) -> Vec<Vec<String>> {
    let account = match posting.ptype {
        PostingType::Regular => posting.account.0.clone(),
        PostingType::Virtual => format!("({})", posting.account.0),
        PostingType::BalancedVirtual => format!("[{}]", posting.account.0),
    };
    // hledger's mixed-amount display drops the zero commodities of a mixed
    // amount (an inferred `[$0.00, -3 AAPL]` prints as `-3 AAPL`), lists the
    // rest in commodity order (its mixed amount is a map keyed on the
    // commodity), and shows an empty one as a bare `0`.
    let mut nonzero: Vec<&Amount> = posting
        .amounts
        .iter()
        .filter(|amount| !amount.quantity.is_zero())
        .collect();
    nonzero.sort_by(|a, b| a.commodity.cmp(&b.commodity));
    let shown: Vec<&Amount> = if nonzero.is_empty() {
        posting.amounts.iter().take(1).collect()
    } else {
        nonzero
    };
    let amounts: Vec<(String, String, Dec)> = if shown.is_empty() {
        vec![("0".to_string(), String::new(), Dec::zero())]
    } else {
        shown.into_iter().map(amount_cells).collect()
    };
    amounts
        .into_iter()
        .map(|(amount, commodity, quantity)| {
            let magnitude = amount.trim_start_matches('-').to_string();
            let (credit, debit) = if quantity.mantissa < 0 {
                (magnitude, String::new())
            } else {
                (String::new(), magnitude)
            };
            vec![
                txn.index.0.to_string(),
                txn.date.clone(),
                txn.date2.clone().unwrap_or_default(),
                status_mark(txn.status).to_string(),
                txn.code.clone(),
                txn.description.clone(),
                txn.comment.trim().to_string(),
                account.clone(),
                amount,
                commodity,
                credit,
                debit,
                status_mark(posting.status).to_string(),
                posting_comment(posting),
            ]
        })
        .collect()
}

/// The `posting-comment` cell. A posting an `=` rule generated inherits the
/// matched posting's dates, and hledger writes them at the front of its
/// comment in bracket syntax — `[DATE]`, `[DATE=DATE2]` or `[=DATE2]` —
/// followed by `, ` and the rule's own comment. Verified on hledger 1.52.
fn posting_comment(posting: &Posting) -> String {
    let comment = posting.comment.trim();
    if posting.generated.is_none() {
        return comment.to_string();
    }
    let dates = match (&posting.date, &posting.date2) {
        (None, None) => return comment.to_string(),
        (Some(date), None) => format!("[{date}]"),
        (Some(date), Some(date2)) => format!("[{date}={date2}]"),
        (None, Some(date2)) => format!("[={date2}]"),
    };
    if comment.is_empty() {
        dates
    } else {
        format!("{dates}, {comment}")
    }
}

/// An amount's `amount` and `commodity` cells, plus its quantity for the
/// credit/debit split.
///
/// The quantity is shown at the amount's own display precision (what was
/// written, or what inference carried — hledger's `asprecision`), widened
/// with zeros when that is longer than the stored scale. It is never
/// rounded: a quantity with more digits than its precision keeps them all,
/// as `print` does. A zero is always a bare `0`, whatever its precision.
fn amount_cells(amount: &Amount) -> (String, String, Dec) {
    let mark = amount.style.decimal_mark.unwrap_or('.');
    let quantity = amount.quantity;
    let precision = amount.style.precision;
    let shown = if quantity.is_zero() {
        Dec::zero()
    } else if precision >= quantity.places || quantity.normalized().places <= precision {
        quantity.rounded(precision).unwrap_or(quantity)
    } else {
        quantity
    };
    (
        render_dec(shown, mark),
        amount.commodity.0.clone(),
        quantity,
    )
}

/// hledger's one-character status marker.
pub(crate) fn status_mark(status: Status) -> &'static str {
    match status {
        Status::Unmarked => "",
        Status::Pending => "!",
        Status::Cleared => "*",
    }
}

/// One CSV record: every field quoted, `"` doubled, `\n` terminated.
fn csv_line<'a>(fields: impl Iterator<Item = &'a str>) -> String {
    let mut line = fields
        .map(|field| format!("\"{}\"", field.replace('"', "\"\"")))
        .collect::<Vec<_>>()
        .join(",");
    line.push('\n');
    line
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse_journal;

    fn export(text: &str) -> CsvExport {
        export_csv(&parse_journal(text, "test.journal").expect("parses"))
    }

    #[test]
    fn header_matches_hledger_1_52() {
        let out = export("");
        assert_eq!(
            out.text,
            "\"txnidx\",\"date\",\"date2\",\"status\",\"code\",\"description\",\"comment\",\
             \"account\",\"amount\",\"commodity\",\"credit\",\"debit\",\"posting-status\",\
             \"posting-comment\"\n"
        );
        assert_eq!((out.transactions, out.rows), (0, 0));
    }

    #[test]
    fn quotes_comments_and_splits_credit_from_debit() {
        let out = export(
            "2024-01-02=2024-01-05 * (101) Grocer  ; note \"q\", a:b\n    expenses:food  $1,234.56  ; p1\n        ; p2\n    ! assets:bank\n",
        );
        let rows: Vec<&str> = out.text.lines().skip(1).collect();
        assert_eq!(
            out.text.split_once('\n').map(|(_, rest)| rest),
            Some(
                "\"1\",\"2024-01-02\",\"2024-01-05\",\"*\",\"101\",\"Grocer\",\"note \"\"q\"\", a:b\",\"expenses:food\",\"1234.56\",\"$\",\"\",\"1234.56\",\"\",\"p1\np2\"\n\
                 \"1\",\"2024-01-02\",\"2024-01-05\",\"*\",\"101\",\"Grocer\",\"note \"\"q\"\", a:b\",\"assets:bank\",\"-1234.56\",\"$\",\"1234.56\",\"\",\"!\",\"\"\n"
            ),
            "{rows:?}"
        );
        assert_eq!((out.transactions, out.rows), (1, 2));
    }

    #[test]
    fn rows_follow_print_order_and_keep_txnidx() {
        let out =
            export("2024-02-01 Later\n    a  1\n    b\n\n2024-01-01 Earlier\n    a  1\n    b\n");
        let first_cells: Vec<&str> = out
            .text
            .lines()
            .skip(1)
            .map(|line| line.split(',').next().unwrap_or_default())
            .collect();
        assert_eq!(first_cells, ["\"2\"", "\"2\"", "\"1\"", "\"1\""]);
    }

    #[test]
    fn virtual_accounts_are_bracketed_and_zero_is_a_debit() {
        let out = export(
            "2024-01-05 V\n    (budget:food)  $10\n    [a]  $5\n    [b]  $-5\n    x  $0\n    y\n",
        );
        let accounts: Vec<String> = out
            .text
            .lines()
            .skip(1)
            .map(|line| line.split("\",\"").nth(7).unwrap_or_default().to_string())
            .collect();
        assert_eq!(accounts, ["(budget:food)", "[a]", "[b]", "x", "y"]);
        assert!(
            out.text
                .contains("\"x\",\"0\",\"$\",\"\",\"0\",\"\",\"\"\n"),
            "{}",
            out.text
        );
    }
}
