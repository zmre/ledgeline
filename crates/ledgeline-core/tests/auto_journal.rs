fn hledger(args: &[&str]) -> Option<std::process::Output> {
    if std::env::var(OPT_IN).is_err() {
        return None;
    }
    Command::new("hledger").args(args).output().ok()
}

/// `hledger bal --auto --flat`, account → total at two places.
fn hledger_bal() -> Option<BTreeMap<String, String>> {
    let file = main_path().to_string_lossy().to_string();
    let out = hledger(&[
        "-f",
        &file,
        "--no-conf",
        "bal",
        "--auto",
        "--flat",
        "--no-total",
        "-O",
        "csv",
    ])?;
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    let csv = String::from_utf8_lossy(&out.stdout).to_string();
    Some(
        csv.lines()
            .skip(1)
            .filter_map(|line| {
                let fields: Vec<&str> = line.split(',').map(|f| f.trim_matches('"')).collect();
                let [account, amount] = fields.as_slice() else {
                    return None;
                };
                let number = amount.replace(['$', ','], "");
                Some((account.to_string(), number))
            })
            .collect(),
    )
}

/// `hledger print --auto` agrees with [`applied_postings_are_hledger_s_print_auto`]
/// posting for posting, read through its CSV output.
#[test]
fn hledger_print_auto_agrees() {
    let file = main_path().to_string_lossy().to_string();
    let Some(out) = hledger(&["-f", &file, "--no-conf", "print", "--auto", "-O", "csv"]) else {
        eprintln!("skipped: set {OPT_IN}=1 (see `just hledger-checks`)");
        return;
    };
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    let csv = String::from_utf8_lossy(&out.stdout).to_string();
    let mut lines = csv.lines();
    let header: Vec<&str> = lines
        .next()
        .expect("header")
        .split(',')
        .map(|f| f.trim_matches('"'))
        .collect();
    let column = |name: &str| header.iter().position(|h| *h == name).expect(name);
    let (account, amount) = (column("account"), column("amount"));
    let theirs: Vec<(String, String)> = lines
        .map(|line| {
            let fields: Vec<&str> = line.split("\",\"").map(|f| f.trim_matches('"')).collect();
            (
                // CSV keeps a virtual posting's parentheses; the model does not.
                fields[account]
                    .trim_matches(['(', ')', '[', ']'])
                    .to_string(),
                fields[amount].replace(['$', ','], ""),
            )
        })
        .collect();
    let ours: Vec<(String, String)> = applied()
        .transactions
        .iter()
        .flat_map(|txn| &txn.postings)
        .map(|posting| {
            let quantity = posting.amounts[0].quantity;
            let text = show(quantity);
            (posting.account.0.clone(), text)
        })
        .collect();
    // hledger prints its own way (`5000.00`, `-1.20`): compare as numbers.
    let numeric = |rows: Vec<(String, String)>| -> Vec<(String, String)> {
        rows.into_iter()
            .map(|(account, amount)| {
                let value: f64 = amount.parse().unwrap_or_else(|_| panic!("{amount}"));
                (account, format!("{value:.3}"))
            })
            .collect()
    };
    assert_eq!(numeric(theirs), numeric(ours));
}
