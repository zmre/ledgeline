/// Decision 9: a rule hledger would refuse the journal over — its regular
/// postings unbalanced, or an amountless leg firing twice in one transaction
/// — is a finding on the transaction, never a refused journal. Decision 11:
/// a rule posting to an account nothing else names is a warning.
#[test]
fn rules_hledger_refuses_are_findings_not_failures() {
    let text = "account assets:checking\naccount expenses:payroll:george\n\
                account expenses:payroll:john\n\n\
                = revenue:sales\n    liabilities:tax  $10\n\n\
                = expenses:payroll\n    expesnes:payroll-tax  *0.1\n    assets:checking\n\n\
                2026-01-01 sale\n    revenue:sales  $-100\n    assets:checking\n\n\
                2026-01-31 payroll\n    expenses:payroll:george  $600\n\
                \x20   expenses:payroll:john  $500\n    assets:checking\n";
    let journal = auto::apply_journal(&parse_journal(text, "/r.journal").expect("parses"));
    let findings = auto::rule_findings(&journal);
    let problems: Vec<(usize, RuleProblem)> = findings
        .into_iter()
        .map(|finding| (finding.rule, finding.problem))
        .collect();
    assert_eq!(
        problems,
        vec![
            (
                0,
                RuleProblem::Unbalanced {
                    position: 0,
                    residual: "$10".to_string()
                }
            ),
            (
                0,
                RuleProblem::UnknownAccount {
                    account: "liabilities:tax".to_string()
                }
            ),
            (
                1,
                RuleProblem::Refused {
                    position: 1,
                    fired: 2
                }
            ),
            (
                1,
                RuleProblem::UnknownAccount {
                    account: "expesnes:payroll-tax".to_string()
                }
            ),
        ]
    );
    // The generic "unbalanced" check reads only WRITTEN postings: the rule's
    // imbalance is reported once, under `auto-rule`, naming the rule.
    let diagnostics =
        serde_json::to_value(wire::journal_to_all_diagnostics(&journal)).expect("json");
    let rules: Vec<&str> = diagnostics
        .as_array()
        .expect("array")
        .iter()
        .map(|d| d["rule"].as_str().expect("rule"))
        .collect();
    assert_eq!(
        rules,
        ["auto-rule", "auto-account", "auto-rule", "auto-account"]
    );
    let message = diagnostics[0]["message"].as_str().expect("message");
    assert!(
        message.contains("`= revenue:sales` (r.journal:5)"),
        "{message}"
    );
    assert!(message.contains("$10"), "{message}");
}

