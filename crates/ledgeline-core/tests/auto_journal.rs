//! The main journal's `=` rules applied as `hledger --auto` applies them
//! (plan 30 Phase 5), over `fixtures/auto-postings/`.
//!
//! Every expected figure below was captured from `hledger 1.52 --auto
//! --no-conf` over the fixture (2026-10-28). With
//! `LEDGELINE_HLEDGER_AUTO_CHECK=1` (`just hledger-checks`) the same
//! comparisons also run against the `hledger` on `PATH`, so a fixture edit
//! cannot quietly drift from what hledger says.

