#!/usr/bin/env python3
"""Write fixtures/saas/startup.journal (plans/37-startup-metrics.md).

The script exists only to write the journal; the journal is the fixture.
Deterministic: no clock, no randomness. Run it from anywhere:

    python3 fixtures/saas/generate.py

Every customer below exercises one path of the startup metrics. The README
lists each story and the figures it pins.
"""

from datetime import date, timedelta
from pathlib import Path

OUT = Path(__file__).resolve().parent / "startup.journal"

# Month 1 is 2025-01, month 18 is 2026-06.
MONTHS = 18
LAST_DAY = date(2026, 6, 30)


def month_start(m: int) -> date:
    """First day of month `m` (1-based from 2025-01)."""
    index = 2025 * 12 + (m - 1)
    return date(index // 12, index % 12 + 1, 1)


def money(cents: int) -> str:
    sign = "-" if cents < 0 else ""
    cents = abs(cents)
    return f"{sign}${cents // 100:,}.{cents % 100:02d}"


SMB = "revenue:subscriptions:smb"
MID = "revenue:subscriptions:mid"
ENT = "revenue:subscriptions:enterprise"

# Monthly-billed customers: name -> list of (first month, last month, leaf,
# monthly amount in dollars). A month with no entry bills nothing.
MONTHLY = {
    # Monthly payer: starts in month 1, expands in month 7.
    "Bluebird Analytics": [(1, 6, MID, 500), (7, 18, MID, 800)],
    # Churns: SMB, churns after month 9.
    "Pinecrest Dental": [(1, 9, SMB, 200)],
    # Contracts: SMB, contracts in month 11.
    "Harbor Yoga": [(1, 10, SMB, 300), (11, 18, SMB, 150)],
    # Reactivates: starts in month 6, a zero month 9 (through 11), back in 12.
    "Lumen Labs": [(6, 8, SMB, 250), (12, 18, SMB, 250)],
    # Mid-market logo: joins in month 10 (services fee below).
    "Granite Health": [(10, 18, MID, 1500)],
    # Changes segment: SMB, moves to enterprise (and upgrades) in month 13.
    "Orbit Freight": [(1, 12, SMB, 400), (13, 18, ENT, 900)],
    # Credit month: billed every month; a larger credit lands in month 8.
    "Fjord Studio": [(1, 18, SMB, 350)],
    # Name variants: spelled `Contoso Ltd.` in month 2 only (see below).
    "Contoso Ltd": [(1, 18, MID, 600)],
}

# Bluebird's metered overage from month 7: usage, never MRR.
USAGE = {"Bluebird Analytics": (7, 18, 100)}

# Spelling override: (customer, month) -> name written in the journal.
SPELLING = {("Contoso Ltd", 2): "Contoso Ltd."}

# Contoso's lines carry a posting-level `class:` that overrides the mid leaf's
# declared `class: direct` (the dimension precedence case).
POSTING_CLASS = {"Contoso Ltd": "partner"}

# Annual prepay: invoiced to deferred revenue, recognised monthly.
# (customer, invoice month, months, annual amount)
ANNUAL = [
    ("Northwind Logistics", 3, 12, 12_000),
    ("Northwind Logistics", 15, 12, 15_600),  # renewal at a higher price
]

# Granite Health's one-off onboarding fee, on its first invoice.
SERVICES = {("Granite Health", 10): 5_000}

# Fjord Studio's service credit in month 8 (larger than the month's charge).
CREDIT = ("Fjord Studio", 8, 500)

# Unattributed: a marketplace payout with two untagged recurring legs (two
# recurring postings, so the payee fallback never applies).
MARKETPLACE = {4: (60, 40), 16: (60, 40)}

FUNDING = 500_000


def sm(m: int) -> int:
    return 2_000 if m <= 9 else 3_000


RND = 4_000
GA = 1_500

HEADER = """\
; generated by fixtures/saas/generate.py, do not edit.
;
; A small SaaS business, 2025-01 through 2026-06, in the structure
; plans/37-startup-metrics.md recommends. See README.md for each customer's
; story and the figures this file pins.

commodity $1,000.00

account assets:bank:operating            ; type: C
account assets:receivable                ; type: A, kpi: receivable
account liabilities:payable              ; type: L, kpi: payable
account liabilities:deferred-revenue     ; type: L, kpi: deferred-revenue
account equity:funding                   ; type: E, cfsection: financing
account revenue                          ; type: R
account revenue:subscriptions            ; type: R, kpi: recurring
account revenue:subscriptions:smb        ; segment: smb, product: core
account revenue:subscriptions:mid        ; segment: mid, product: core, class: direct
account revenue:subscriptions:enterprise  ; segment: enterprise, product: platform
account revenue:usage                    ; kpi: usage
account revenue:services
account expenses                         ; type: X
account expenses:cogs:hosting            ; issection: cogs
account expenses:sales-marketing         ; kpi: sales-marketing
account expenses:rnd                     ; kpi: rnd
account expenses:ga                      ; kpi: ga
"""


class Journal:
    def __init__(self) -> None:
        self.entries: list[tuple[date, int, str]] = []
        self.seq = 0

    def add(self, when: date, description: str, postings: list[tuple[str, int, str]]) -> None:
        """`postings`: (account, cents, comment). Amounts must balance."""
        assert sum(p[1] for p in postings) == 0, (when, description, postings)
        lines = [f"{when.isoformat()} {description}"]
        for account, cents, comment in postings:
            line = f"    {account:<36}  {money(cents):>14}"
            if comment:
                line += f"  ; {comment}"
            lines.append(line)
        self.seq += 1
        self.entries.append((when, self.seq, "\n".join(lines)))

    def render(self) -> str:
        body = "\n\n".join(text for _, _, text in sorted(self.entries))
        return HEADER + "\n" + body + "\n"


def leaf_for(customer: str, m: int) -> tuple[str, int] | None:
    for first, last, leaf, amount in MONTHLY.get(customer, []):
        if first <= m <= last:
            return leaf, amount
    return None


def main() -> None:
    j = Journal()
    j.add(
        date(2025, 1, 2),
        "Seed round",
        [("assets:bank:operating", FUNDING * 100, ""), ("equity:funding", -FUNDING * 100, "")],
    )

    for m in range(1, MONTHS + 1):
        first = month_start(m)

        # Monthly invoices through receivables, collected 30 days later.
        for customer in MONTHLY:
            billed = leaf_for(customer, m)
            if billed is None:
                continue
            leaf, amount = billed
            name = SPELLING.get((customer, m), customer)
            tag = f"customer: {name}"
            if customer in POSTING_CLASS:
                tag += f", class: {POSTING_CLASS[customer]}"
            lines = [(leaf, -amount * 100, tag)]
            usage = USAGE.get(customer)
            if usage and usage[0] <= m <= usage[1]:
                lines.append(("revenue:usage", -usage[2] * 100, f"customer: {name}"))
            fee = SERVICES.get((customer, m))
            if fee:
                lines.append(("revenue:services", -fee * 100, f"customer: {name}"))
            total = -sum(cents for _, cents, _ in lines)
            j.add(first, f"{name} | Invoice {first:%Y-%m}", [("assets:receivable", total, "")] + lines)
            paid = first + timedelta(days=30)
            if paid <= LAST_DAY:
                j.add(
                    paid,
                    f"{name} | Payment for {first:%Y-%m}",
                    [("assets:bank:operating", total, ""), ("assets:receivable", -total, "")],
                )

        # Annual prepay: invoice to deferred, recognise monthly.
        for customer, invoice_month, months, annual in ANNUAL:
            if m == invoice_month:
                j.add(
                    first,
                    f"{customer} | Annual subscription {first:%Y-%m}",
                    [
                        ("assets:receivable", annual * 100, ""),
                        ("liabilities:deferred-revenue", -annual * 100, f"customer: {customer}"),
                    ],
                )
                j.add(
                    first + timedelta(days=30),
                    f"{customer} | Payment for annual subscription",
                    [("assets:bank:operating", annual * 100, ""), ("assets:receivable", -annual * 100, "")],
                )
            if invoice_month <= m < invoice_month + months:
                monthly = annual * 100 // months
                j.add(
                    first,
                    f"{customer} | Revenue recognition {first:%Y-%m}",
                    [
                        ("liabilities:deferred-revenue", monthly, ""),
                        (ENT, -monthly, f"customer: {customer}"),
                    ],
                )

        if m == CREDIT[1]:
            j.add(
                first.replace(day=15),
                f"{CREDIT[0]} | Service credit",
                [
                    (SMB, CREDIT[2] * 100, f"customer: {CREDIT[0]}"),
                    ("assets:bank:operating", -CREDIT[2] * 100, ""),
                ],
            )

        if m in MARKETPLACE:
            smb, mid = MARKETPLACE[m]
            j.add(
                first.replace(day=10),
                "Marketplace payout",
                [
                    ("assets:bank:operating", (smb + mid) * 100, ""),
                    (SMB, -smb * 100, ""),
                    (MID, -mid * 100, ""),
                ],
            )

        # Operating expenses, paid from the bank on the 15th.
        for account, payee, amount in [
            ("expenses:sales-marketing", "Adwise Media", sm(m)),
            ("expenses:rnd", "Payroll | Engineering", RND),
            ("expenses:ga", "Payroll | Operations", GA),
        ]:
            j.add(
                first.replace(day=15),
                payee,
                [(account, amount * 100, ""), ("assets:bank:operating", -amount * 100, "")],
            )

    # Hosting: 20% of the month's MRR, billed on the 20th, paid 15 days later.
    for m in range(1, MONTHS + 1):
        mrr = monthly_mrr_cents(m)
        bill = mrr // 5
        when = month_start(m).replace(day=20)
        j.add(
            when,
            "Cloudnine Hosting | Hosting bill",
            [("expenses:cogs:hosting", bill, ""), ("liabilities:payable", -bill, "")],
        )
        paid = when + timedelta(days=15)
        if paid <= LAST_DAY:
            j.add(
                paid,
                "Cloudnine Hosting | Bill payment",
                [("liabilities:payable", bill, ""), ("assets:bank:operating", -bill, "")],
            )

    OUT.write_text(j.render())


def monthly_mrr_cents(m: int) -> int:
    """MRR for month `m`, from the same tables the entries are written from."""
    total = 0
    for customer in MONTHLY:
        billed = leaf_for(customer, m)
        if billed:
            total += billed[1] * 100
    for _, invoice_month, months, annual in ANNUAL:
        if invoice_month <= m < invoice_month + months:
            total += annual * 100 // months
    if m == CREDIT[1]:
        total -= CREDIT[2] * 100
    if m in MARKETPLACE:
        total += sum(MARKETPLACE[m]) * 100
    return total


if __name__ == "__main__":
    main()
